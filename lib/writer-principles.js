function resolveFormat(format) {
  return FORMAT_PRINCIPLES[format] ? format : "straight";
}

function buildArticleInstructions(format) {
  const selected = resolveFormat(format);
  const profile = FORMAT_PRINCIPLES[selected];
  return `${COMMON_PRINCIPLES}\n[형식 방화벽]\n이번 기사는 ‘${profile.label}’로만 쓴다. 선택하지 않은 기사 형식의 도입·전개·종결 규칙을 섞지 않는다.\n${profile.text}`.trim();
}

