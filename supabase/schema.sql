-- PEF Monitor 초기 저장 스키마
-- Supabase Dashboard > SQL Editor에서 실행

create table if not exists public.disclosures (
  id bigint generated by default as identity primary key,

  rcept_no text not null unique,
  corp_code text,
  corp_name text not null,
  report_nm text not null,
  filer_name text,
  receipt_date date not null,

  dart_url text,
  event_type text,
  importance smallint check (importance between 1 and 5),
  why_watch text,

  related_companies jsonb not null default '[]'::jsonb,
  related_disclosures jsonb not null default '[]'::jsonb,
  raw_data jsonb not null default '{}'::jsonb,

  first_seen_at timestamptz not null default now(),
  last_updated_at timestamptz not null default now()
);

create index if not exists disclosures_receipt_date_idx
on public.disclosures (receipt_date desc);

create index if not exists disclosures_corp_name_idx
on public.disclosures (corp_name);

create index if not exists disclosures_event_type_idx
on public.disclosures (event_type);

create table if not exists public.monitor_runs (
  id bigint generated by default as identity primary key,

  source text not null default 'dart',
  status text not null,
  fetched_count integer not null default 0,
  saved_count integer not null default 0,
  error_message text,

  started_at timestamptz not null default now(),
  completed_at timestamptz
);

alter table public.disclosures enable row level security;
alter table public.monitor_runs enable row level security;

-- 기사 후보: 공시 원문(raw_data)과 분리해 점수·취재 질문을 바로 조회한다.
create table if not exists public.article_candidates (
  rcept_no text primary key references public.disclosures(rcept_no) on delete cascade,
  corp_code text,
  corp_name text not null,
  event_id text not null,
  event_type text not null,
  deal_stage text,
  story_score smallint not null check (story_score between 0 and 100),
  story_bucket text not null check (story_bucket in ('story', 'verify', 'archive')),
  headline text,
  change_summary text,
  why_story text,
  key_numbers jsonb not null default '[]'::jsonb,
  call_targets jsonb not null default '[]'::jsonb,
  reporter_questions jsonb not null default '[]'::jsonb,
  article_angles jsonb not null default '[]'::jsonb,
  score_breakdown jsonb not null default '{}'::jsonb,
  evidence jsonb not null default '{}'::jsonb,
  workflow_status text not null default 'new',
  reporter_note text,
  first_seen_at timestamptz not null default now(),
  last_updated_at timestamptz not null default now()
);

create index if not exists article_candidates_priority_idx
on public.article_candidates (story_bucket, story_score desc, last_updated_at desc);

create index if not exists article_candidates_corp_idx
on public.article_candidates (corp_code, last_updated_at desc);

-- 기업·운용사·SPC를 하나의 개체로 관리한다.
create table if not exists public.entities (
  id uuid primary key default gen_random_uuid(),
  canonical_name text not null,
  entity_type text not null default 'company',
  dart_corp_code text,
  stock_code text,
  aliases jsonb not null default '[]'::jsonb,
  watch_priority smallint not null default 0,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists entities_dart_corp_code_uidx
on public.entities (dart_corp_code) where dart_corp_code is not null;

create index if not exists entities_name_idx
on public.entities (canonical_name);

-- 하나의 거래에 여러 공시·뉴스·관계자를 묶는다.
create table if not exists public.deals (
  id uuid primary key default gen_random_uuid(),
  deal_key text not null unique,
  deal_name text not null,
  deal_type text,
  current_stage text,
  status text not null default 'watching',
  target_entity_id uuid references public.entities(id),
  estimated_value numeric,
  currency text not null default 'KRW',
  summary text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.deal_events (
  id bigint generated by default as identity primary key,
  deal_id uuid references public.deals(id) on delete cascade,
  rcept_no text references public.disclosures(rcept_no) on delete set null,
  event_date date not null,
  event_type text not null,
  stage_before text,
  stage_after text,
  headline text,
  facts jsonb not null default '[]'::jsonb,
  changes jsonb not null default '[]'::jsonb,
  evidence jsonb not null default '[]'::jsonb,
  confidence smallint not null default 3 check (confidence between 1 and 5),
  created_at timestamptz not null default now()
);

create index if not exists deal_events_timeline_idx
on public.deal_events (deal_id, event_date desc);

create table if not exists public.entity_relations (
  id bigint generated by default as identity primary key,
  from_entity_id uuid not null references public.entities(id) on delete cascade,
  to_entity_id uuid not null references public.entities(id) on delete cascade,
  relation_type text not null,
  deal_id uuid references public.deals(id) on delete set null,
  basis text,
  confidence smallint not null default 3 check (confidence between 1 and 5),
  valid_from date,
  valid_to date,
  source_rcept_no text references public.disclosures(rcept_no) on delete set null,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists entity_relations_from_idx on public.entity_relations (from_entity_id);
create index if not exists entity_relations_to_idx on public.entity_relations (to_entity_id);

-- 기사·보도자료·공시의 출처와 검증 가능한 사실을 분리한다.
create table if not exists public.source_documents (
  id uuid primary key default gen_random_uuid(),
  source_type text not null,
  source_name text,
  title text not null,
  source_url text,
  published_at timestamptz,
  excerpt text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.fact_claims (
  id bigint generated by default as identity primary key,
  subject_entity_id uuid references public.entities(id) on delete cascade,
  deal_id uuid references public.deals(id) on delete cascade,
  predicate text not null,
  value jsonb not null,
  source_document_id uuid references public.source_documents(id) on delete set null,
  source_rcept_no text references public.disclosures(rcept_no) on delete set null,
  verification_status text not null default 'unverified',
  valid_from date,
  valid_to date,
  created_at timestamptz not null default now()
);

create index if not exists fact_claims_subject_idx
on public.fact_claims (subject_entity_id, predicate);

-- 공시별 국내뉴스·외신·보도자료. 원문 전체가 아니라 제목·링크·짧은 설명만 저장한다.
create table if not exists public.related_sources (
  id bigint generated by default as identity primary key,
  rcept_no text not null references public.disclosures(rcept_no) on delete cascade,
  corp_code text,
  corp_name text not null,
  category text not null check (category in ('domestic', 'foreign', 'press_release')),
  source_name text,
  title text not null,
  source_url text not null,
  published_at timestamptz,
  snippet text,
  language text,
  provider text,
  metadata jsonb not null default '{}'::jsonb,
  first_seen_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  unique (rcept_no, source_url)
);

create index if not exists related_sources_candidate_idx
on public.related_sources (rcept_no, category, published_at desc);

create index if not exists related_sources_company_idx
on public.related_sources (corp_code, published_at desc);

alter table public.article_candidates enable row level security;
alter table public.entities enable row level security;
alter table public.deals enable row level security;
alter table public.deal_events enable row level security;
alter table public.entity_relations enable row level security;
alter table public.source_documents enable row level security;
alter table public.fact_claims enable row level security;
alter table public.related_sources enable row level security;
